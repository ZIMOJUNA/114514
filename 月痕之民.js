// ── 5. `世界`（总表 §4） ────────────────────────────────────────────────────
const 世界Schema = 对象({
  历法: 对象({
    年: 整数(1, 9999, 1916),      // 新月历 1916 年（开拓纪元中期）
    月: 整数(1, 12, 1),           // 每月固定 30 天
    日: 整数(1, 30, 1),           // ＋年末「新月祭典期」5 天
    星期: 枚举(['星期一', '星期二', '星期三', '星期四', '星期五', '星期六', '星期日'], '星期一'),
  }),
  // 🔴 `星期` 是纯函数却要存（驾驶员 2026-09-18 裁「存吧」）
  //    ⇒ 「换日时必须同时改 `星期`」那条规矩写在 `[mvu_update]变量更新规则` 里，
  //      **schema 里不挂跨字段重算**（总表 §9.3：参考卡一条跨字段都不做）。

  // 🆕 `B3` —— **`时刻` 是真源，`时段` 整格撤掉**（驾驶员 2026-09-18 裁
  //    「不用了，ai 自己会判断的」）。
  //    🔴 理由：①「清晨/傍晚」是**叙事用语不是设定**，`1090` 只写「24 个标准魔导时」；
  //      ② 钉死一张"15 点必须叫下午"的派生表 **= 造第二个真源**，两者能对不上而 schema 抓不出
  //         （同 `星期` 那格的代价）—— **而 `星期` 那处是有卡文才付的，时段卡里没有那句话**；
  //      ③ `时刻` 本身有实打实的读者：`14080` 的 `日` 结算、`1112` 的超期、`1113` 的昼夜差异。
  //    ⚠ **`0`~`23` 逐字对齐 `1090` 的「每日严格划分为 24 个标准魔导时」**，
  //      不是创世那套 9 档 —— 24 ÷ 9 不是整数，两套本来就对不上。
  时刻: 整数(0, 23, 8),
  // 🆕 `B3` 照道渊 `世界.危机程度` 五档。
  //    ⚠ **道渊那格的教训**：它 zod 里写的是 `z.string()`，**没上 enum**
  //      ⇒ 那是**它自己没做完，不是"该用 string"**。这里上 enum。
  危机: 枚举(['无', '低', '中', '高', '致命'], '无'),

  地点: 串(''),
  // 🆕 `B5` 丙 —— 与 `地点` 并存的第二格。
  //    🔴 存在的理由只有一条：`1113` 六、明写「**地点必须挂在一个已生成的大区之下**」。
  //      纯字符串守不住这条（甲），拆成 `{大陆,区域,场所}` 又把**临时真源**硬化成结构（乙）。
  //      ⇒ 单拎一格，刚好落在中间。空串 = 不在任何已生成大区内。
  //    ⚠ **代价是已知且本卡已接受过的**：句子里第一段与这一格可能对不上，schema 抓不出
  //      —— 同 `星期` 那格。⇒ 配一条规则：「`大区` 为空 ⇒ 不得生成地点」。
  大区: 串(''),

  新闻: 新闻Schema,               // 🆕 `B3` 整体照命定 —— 三组固定槽位，**18 格**（§4.6）
  局势: 字典(局势条目Schema),     // 🆕 `B3` 丙 · 1 格
  // 🔧 `B2` —— 值从 `string` 长成对象，**容器类型不变**（`D73` ④⑦ 那个占位本来就写成字典）
  主线: 字典(主线条目Schema),
});


