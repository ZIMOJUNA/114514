const 串 = (默认 = '') => z.string().catch(默认).prefault(默认);
const 数 = (最小, 最大, 默认 = 0) =>
  z.coerce.number().catch(默认)
    .transform(v => (isNaN(v) ? 默认 : _.clamp(v, 最小, 最大)))
    .prefault(默认);
const 整数 = (最小, 最大, 默认 = 0) =>
  z.coerce.number().catch(默认)
    .transform(v => (isNaN(v) ? 默认 : _.clamp(Math.trunc(v), 最小, 最大)))
    .prefault(默认);
const 枚举 = (可选值, 默认) =>
  z.enum(可选值).catch(默认).prefault(默认);
const 开关 = (默认 = false) => z.coerce.boolean().catch(默认).prefault(默认);
const 字典 = (值schema) => z.record(z.string(), 值schema).catch({}).prefault({});
const 对象 = (形状) => z.object(形状).catch({}).prefault({});
const 属性词条Schema = z.array(z.object({
  入口: 枚举(['常驻', '触发', '主动', '反应'], '常驻'),
  极性: 枚举(['正', '负'], '正'),
  写法: 枚举(['检定修正', '资源%', '精神类'], '检定修正'),
  值: z.union([z.string(), z.coerce.number()]).catch('').prefault(''),
})).catch([]).prefault([]);
